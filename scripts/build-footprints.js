'use strict';

const fs = require('node:fs');
const path = require('node:path');
const specs = require('./lib/switches');
const makeFootprint = require('./lib/footprint-template');
const { sourceContours, fitContour, TOLERANCE } = require('./lib/geometry');
const root = path.resolve(__dirname, '..');
const destination = path.join(root, 'ergogen/footprints');

function build(check = false) {
  fs.mkdirSync(destination, { recursive: true });
  for (const spec of specs) {
    const source = sourceContours(root, spec.study);
    const fitted = source.map(fitContour);
    const contours = fitted.map(contour => contour.map(({ type, start, mid, end }) =>
      ({ type, start, ...(mid ? { mid } : {}), end })));
    const content = `// Generated by scripts/build-footprints.js; edit scripts/lib/ sources instead.\n` +
      `// Study: keyboard-flex-study/key-flex-cuts.html, ${spec.study}-title.\n` +
      `// Contour fit tolerance: ${TOLERANCE} mm. Ergogen >=4.1.0, template: kicad8.\n` +
      `// from -> pin 1; to -> pin 2. Top-mounted switch, B.Cu/B.Mask solder pads.\n` +
      `module.exports = (${makeFootprint.toString()})(\n${JSON.stringify(spec, null, 2)},\n${JSON.stringify(contours, null, 2)}\n);\n`;
    const filename = path.join(destination, `${spec.id}.js`);
    if (check) {
      if (fs.readFileSync(filename, 'utf8') !== content) throw new Error(`Stale footprint: ${spec.id}`);
    } else fs.writeFileSync(filename, content);
    console.log(`${spec.id}: ${source.length} closed cuts, ${source.reduce((n, c) => n + c.length - 1, 0)} study edges -> ${contours.flat().length} lines/arcs`);
  }
}

if (require.main === module) build(process.argv.includes('--check'));
module.exports = { build };
